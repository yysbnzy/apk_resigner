def _load_original_tool():
    code = marshal.loads(zlib.decompress(base64.b85decode(_ORIGINAL_CODE)))
    module = types.ModuleType("serial_tool_original")
    module.__file__ = __file__
    exec(code, module.__dict__)
    return module


_original = _load_original_tool()
_OriginalSerialDebugTool = _original.SerialDebugTool


def _port_text(port):
    """下拉框显示 COM 口和设备描述，内部始终保留真实 device。"""
    description = (port.description or "").strip()
    if not description or description == port.device:
        return port.device
    return f"{port.device} ({description})"


def _sync_selected_port(self, _event=None):
    selected = self.cb_port.get()
    device = self._port_display_map.get(selected, selected.split(" (", 1)[0])
    self.var_port.set(device)


def refresh_ports_with_description(self):
    """刷新串口列表，格式：COM13 (USB Serial Port (COM13))。"""
    ports = sorted(list_ports.comports(), key=lambda p: p.device)
    self._port_display_map = {_port_text(port): port.device for port in ports}
    display_values = list(self._port_display_map)
    self.cb_port.configure(values=display_values)

    current_device = self.var_port.get().strip()
    current_display = next(
        (text for text, device in self._port_display_map.items()
         if device == current_device),
        "",
    )
    if not current_display and display_values:
        current_display = display_values[0]
        current_device = self._port_display_map[current_display]
        self.var_port.set(current_device)

    self.cb_port.set(current_display or current_device)


_OriginalSerialDebugTool.refresh_ports = refresh_ports_with_description


class SerialToolFrame(ttk.Frame):
    """将原 SerialDebugTool 嵌入 Notebook，而非创建独立 Tk 窗口。"""

    def __init__(self, parent):
        super().__init__(parent)
        self._serial_closed = False
        self.backend = _OriginalSerialDebugTool(self)
        self.backend.cb_port.configure(textvariable=tk.StringVar())
        self.backend.cb_port.bind(
            "<<ComboboxSelected>>",
            lambda event: _sync_selected_port(self.backend, event),
        )
        self.backend.refresh_ports()
        self.bind("<Destroy>", self._on_destroy, add="+")

    # 原工具面向独立 Tk 根窗口；嵌入后由 APK 主窗口统一管理。
    def title(self, *_args):
        return None

    def geometry(self, *_args):
        return None

    def protocol(self, *_args):
        return None

    def _on_destroy(self, event):
        if event.widget is not self or self._serial_closed:
            return
        self._serial_closed = True
        try:
            self.backend.on_closing()
        except (tk.TclError, RuntimeError):
            pass
